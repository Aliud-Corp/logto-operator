// Command specwindow writes what is derived from the vendored specs of the support window (api/logto/versions.txt):
// each version's normalized spec (api/logto/<version>.normalized.json, what the tests load) and the fingerprints
// logtoctl recognises a target's version by (internal/logto/version/fingerprints.gen.go). Run by `task generate`.
//
// Usage: go run ./tools/specwindow <api/logto dir> <fingerprints.gen.go>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/Aliud-Corp/logto-operator/internal/logto/openapi"
	"github.com/Aliud-Corp/logto-operator/internal/logto/version"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: specwindow <api/logto dir> <fingerprints.gen.go>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "specwindow:", err)
		os.Exit(1)
	}
}

func run(dir, out string) error {
	list, err := os.ReadFile(filepath.Join(dir, "versions.txt"))
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/specwindow from api/logto/versions.txt. DO NOT EDIT.\n\npackage version\n\n")
	b.WriteString("// supported is the support window, newest first, with each vendored spec's fingerprint.\n")
	b.WriteString("var supported = []struct{ version, fingerprint string }{\n")
	for _, v := range strings.Fields(string(list)) {
		raw, err := os.ReadFile(filepath.Join(dir, v+".openapi.json"))
		if err != nil {
			return err
		}
		print, err := version.Fingerprint(raw)
		if err != nil {
			return fmt.Errorf("%s: %w", v, err)
		}
		norm, err := openapi.Normalize(raw)
		if err != nil {
			return fmt.Errorf("%s: %w", v, err)
		}
		if err := os.WriteFile(filepath.Join(dir, v+".normalized.json"), norm, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&b, "\t{%q, %q},\n", v, print)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}
